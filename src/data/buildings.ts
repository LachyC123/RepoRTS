import type { Cost, ResKey } from './constants';

export type BuildingCategory = 'core' | 'economy' | 'military' | 'defence' | 'civic' | 'landmark';

export interface BuildingDef {
  id: string;
  name: string;
  desc: string;
  category: BuildingCategory;
  /** footprint in tiles */
  size: number;
  hp: number;
  /** damage multipliers by attack type */
  armor: { melee: number; pierce: number; siege: number };
  cost: Cost;
  buildTime: number;
  /** minimum settlement tier to construct */
  tier: number;
  /** production per minute while staffed */
  produces?: Partial<Record<ResKey, number>>;
  /** requires a deposit/feature near the plot */
  requires?: 'forest' | 'gold' | 'stone' | 'mineral' | 'fertile';
  popCap?: number;
  vision?: number;
  /** ranged defence */
  defence?: { attack: number; range: number; cooldown: number };
  workers?: number;
  /** can only be placed by systems, not from the build menu */
  system?: boolean;
  /** upgrades researchable here */
  researches?: string[];
  /** AI/UI hint shown in menu */
  hint: string;
}

