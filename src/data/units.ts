export const TRAINABLE_UNITS = Object.values(UNITS).filter((u) => !u.special);
export const MERCENARY_UNITS = Object.values(UNITS).filter((u) => u.special === 'mercenary');

export function unitHasTag(def: UnitDef, tag: UnitTag) {
  return def.tags.includes(tag);
}

/** Broad class used for formation placement and AI composition. */
export function unitClass(def: UnitDef): 'melee' | 'ranged' | 'cavalry' | 'siege' {
  if (def.tags.includes('siege')) return 'siege';
  if (def.tags.includes('cavalry')) return 'cavalry';
  if (def.tags.includes('ranged')) return 'ranged';
  return 'melee';
}
