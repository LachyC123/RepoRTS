import { TILE, type Cost } from './constants';

export type UnitTag =
  | 'infantry'
  | 'heavy'
  | 'spear'
  | 'ranged'
  | 'cavalry'
  | 'siege'
  | 'commander'
  | 'worker'
  | 'beast'
  | 'building'
  | 'light';

export type AttackType = 'melee' | 'pierce' | 'siege';
export type ProjectileKind = 'arrow' | 'bolt' | 'rock' | 'bigrock' | 'ballista';

/** Visual description of a soldier. Consumed by the procedural sprite generator (render/art/unitArt.ts).
 *  Swapping in real art means replacing the generator output; gameplay never reads these. */
export interface UnitLook {
  body: 'peasant' | 'soldier' | 'heavy' | 'beast' | 'engine';
  helmet: 'none' | 'hood' | 'cap' | 'kettle' | 'nasal' | 'great' | 'crown' | 'feather';
  armor: 'tunic' | 'gambeson' | 'mail' | 'plate' | 'robe' | 'leather';
  weapon: 'none' | 'club' | 'spear' | 'sword' | 'axe' | 'bow' | 'crossbow' | 'pike' | 'longbow' | 'lance' | 'greatsword' | 'pitchfork';
  shield: 'none' | 'round' | 'kite' | 'tower' | 'buckler';
  mount?: 'horse' | 'warhorse' | 'pony';
  engine?: 'ram' | 'catapult' | 'ballista' | 'trebuchet';
  cape?: boolean;
  beard?: boolean;
  /** skin/cloth tint hints */
  cloth?: string;
}

export interface UnitDef {
  id: string;
  name: string;
  plural: string;
  desc: string;
  role: string;
  tags: UnitTag[];
  hp: number;
  attack: number;
  attackType: AttackType;
  /** seconds between attacks */
  cooldown: number;
  /** wind-up before damage is applied (seconds) */
  windup: number;
  /** world px. Melee ~ 6. */
  range: number;
  minRange?: number;
  armor: { melee: number; pierce: number };
  /** pierce/siege armour ignored */
  armorPen?: number;
  /** world px per second */
  speed: number;
  /** tiles */
  vision: number;
  /** collision radius in world px */
  radius: number;
  bonus?: Partial<Record<UnitTag, number>>;
  /** area damage radius (siege) */
  splash?: number;
  projectile?: ProjectileKind;
  /** accuracy vs moving targets 0..1 */
  accuracy?: number;
  /** cavalry charge multiplier on first strike after running */
  charge?: number;
  /** trebuchet: seconds to (un)pack */
  deploy?: number;
  /** only attacks buildings */
  buildingsOnly?: boolean;
  cost: Cost;
  pop: number;
  trainTime: number;
  /** building that trains it */
  trainedAt: string[];
  /** minimum settlement tier of the training building's settlement */
  tier: number;
  /** strategic military value for AI strength estimates */
  power: number;
  look: UnitLook;
  /** mercenary/neutral units are not trainable normally */
  special?: 'mercenary' | 'neutral' | 'commander';
}

